/* inner-organs.js —— 内脏各系统：呼吸、心脏与大血管、消化、泌尿、生殖、内分泌、脑与脊髓、淋巴
 * 位置全部按躯干截面现算，所以改身高体重三围时内脏跟着躯干一起动
 */
(function () {
  'use strict';

  var V = THREE.Vector3;

  function build(cx) {
    var H = cx.H, item = cx.item, ell = cx.ell, tube = cx.tube, poly = cx.poly;

    /** 躯干里的一点：x 用身高比例，zt 是「前深占比」——0 在椎体上，1 在前面的皮肤上 */
    function T(xf, f, zt) {
      var s = cx.sec(f), zb = cx.spineZ(f);
      return new V(xf * H, f * H, zb + (s.bF - zb) * zt);
    }
    /** 同上，但 x 用「半宽占比」：±1 就是体侧的皮肤（胖瘦一变，肺和肾跟着挪） */
    function W(xa, f, zt) {
      var s = cx.sec(f), zb = cx.spineZ(f);
      return new V(xa * s.a, f * H, zb + (s.bF - zb) * zt);
    }
    function A(f) { return cx.sec(f).a; }

    /* ---------------- 呼吸 ---------------- */
    [1, -1].forEach(function (side) {
      var sn = side > 0 ? '左' : '右';
      item('resp', sn + '扁桃体', [ell(T(side * 0.013, 0.874, 0.34),
        0.007 * H, 0.011 * H, 0.006 * H, null, 12)],
        { side: sn, note: '张嘴能看到的、舌根两侧那两团；发炎肿大时吞咽刀割一样痛' });
    });
    item('resp', '喉(含声带)', [ell(T(0, 0.852, 0.62), 0.014 * H, 0.017 * H, 0.013 * H, null, 14)],
      { note: '男性这里前突就是喉结；感冒时说话痛、吞咽痛多在这一段' });
    var trTop = T(0, 0.842, 0.42), trBot = T(0, 0.744, 0.40);
    item('resp', '气管', [poly([trTop, T(0, 0.800, 0.41), trBot], 0.0085 * H, 10)],
      { note: '从喉一直下到胸腔中央，在心脏上方分成左右两支' });
    [1, -1].forEach(function (side) {
      var sn = side > 0 ? '左' : '右';
      item('resp', sn + '主支气管', [poly([trBot,
        new V(side * 0.016 * H, 0.730 * H, trBot.z - 0.004 * H),
        new V(side * 0.030 * H, 0.714 * H, trBot.z - 0.010 * H)], 0.0060 * H, 8)],
        { side: sn, note: side < 0 ? '右侧更粗更直，误吞的东西多掉进这一侧' : '' });
    });

    /* 肺：右三叶、左两叶。左肺被心脏挤掉一块，所以窄一点 */
    var LOBE = [
      { s: -1, nm: '右肺上叶', f: 0.762, ry: 0.028, kx: 0.90 },
      { s: -1, nm: '右肺中叶', f: 0.710, ry: 0.017, kx: 0.90 },
      { s: -1, nm: '右肺下叶', f: 0.676, ry: 0.026, kx: 0.90 },
      { s: 1, nm: '左肺上叶', f: 0.754, ry: 0.032, kx: 0.80 },
      { s: 1, nm: '左肺下叶', f: 0.682, ry: 0.030, kx: 0.80 }
    ];
    LOBE.forEach(function (lo) {
      var a = A(lo.f), s = cx.sec(lo.f), zb = cx.spineZ(lo.f);
      var c = W(lo.s * 0.52 * lo.kx, lo.f, 0.46);
      item('resp', lo.nm, [ell(c, a * 0.34 * lo.kx, lo.ry * H, (s.bF - zb) * 0.34, null, 16)],
        { side: lo.s > 0 ? '左' : '右', note: lo.nm.indexOf('下叶') > 0 ? '肺的底面是斜的：背后能低到第 10 肋，前面只到第 6 肋' : '' });
    });

    /* ---------------- 心脏与大血管主干 ----------------
       心脏不在正中：约 2/3 偏在身体左侧，尖朝左前下，所以左侧第 5 肋间能摸到跳动 */
    var hBase = T(0.006, 0.726, 0.52), hApex = T(0.038, 0.662, 0.60);
    item('heart', '心脏', [tube(hBase, hApex, 0.042 * H, 0.010 * H, { seg: 20, steps: 6, round0: true, round1: true })],
      { note: '尖朝左前下，跳动最明显的位置在左乳下方偏内' });
    var arch = T(0, 0.766, 0.30);
    item('heart', '主动脉', [poly([T(0.006, 0.716, 0.50), T(0.004, 0.748, 0.40), arch,
      T(-0.008, 0.756, 0.16), T(-0.004, 0.700, 0.12), T(-0.004, 0.620, 0.12), T(-0.002, 0.566, 0.12)], 0.0105 * H, 10)],
      { note: '心脏泵出去的总管，绕一个弓再贴着脊柱往下走，到肚子里分成两条去下肢' });
    item('heart', '肺动脉', [poly([T(0.014, 0.730, 0.44), T(0.006, 0.748, 0.34),
      new V(-0.022 * H, 0.742 * H, arch.z - 0.006 * H)], 0.0080 * H, 8)],
      { note: '把血送进肺去换气的那一支' });
    item('heart', '上腔静脉', [poly([T(-0.020, 0.766, 0.36), T(-0.016, 0.732, 0.44)], 0.0080 * H, 8)],
      { note: '收上半身的回流血，从右上方进入心脏' });
    item('heart', '下腔静脉', [poly([T(-0.014, 0.712, 0.42), T(-0.012, 0.660, 0.22),
      T(-0.012, 0.600, 0.16), T(-0.014, 0.556, 0.14)], 0.0090 * H, 8)],
      { note: '收下半身的回流血，在脊柱右前方上行' });
    /* ---------------- 消化 ----------------
       注意左右：人体自身右侧是 −X，所以肝、升结肠、阑尾都在 x 为负那一边 */
    item('dig', '食管', [poly([T(0, 0.840, 0.28), T(0, 0.760, 0.26), T(0, 0.690, 0.30),
      T(0.008, 0.660, 0.40), T(0.012, 0.650, 0.46)], 0.0075 * H, 8)],
      { note: '穿过膈肌进胃；胃酸反上来时烧的就是它的下段' });

    var pyl = T(-0.010, 0.616, 0.50);
    item('dig', '胃', [poly([T(0.012, 0.652, 0.48), T(0.038, 0.648, 0.42), T(0.046, 0.624, 0.50),
      T(0.024, 0.606, 0.56), pyl], 0.026 * H, 14)],
      { note: '大部分在左上腹、肋弓下面，不在肚脐那儿' });
    item('dig', '肝脏', [
      ell(W(-0.52, 0.646, 0.54), A(0.646) * 0.44, 0.030 * H, (cx.sec(0.646).bF - cx.spineZ(0.646)) * 0.34, null, 16),
      ell(T(0.016, 0.650, 0.58), 0.028 * H, 0.017 * H, 0.020 * H, null, 14)
    ], { note: '主要在右侧肋弓下方，正常摸不到；右上腹的钝痛常和它有关' });
    item('dig', '胆囊', [ell(T(-0.026, 0.630, 0.62), 0.010 * H, 0.015 * H, 0.011 * H, null, 14)],
      { note: '贴在肝脏下面；胆结石发作是右上腹绞痛，有时串到右肩背' });
    item('dig', '胰', [poly([W(-0.32, 0.628, 0.28), T(0, 0.634, 0.26), W(0.56, 0.640, 0.24)], 0.0095 * H, 8)],
      { note: '横躺在胃后面，贴着脊柱；分泌消化液，也管血糖（胰岛在它里面）' });
    item('dig', '十二指肠', [poly([pyl, T(-0.026, 0.610, 0.42), T(-0.022, 0.592, 0.38),
      T(0, 0.594, 0.42), T(0.012, 0.600, 0.46)], 0.0105 * H, 8)],
      { note: '胃出口后的第一段，绕着胰头拐一个 C 形' });

    var coil = [];
    for (var si = 0; si <= 12; si++) {
      var st = si / 12;
      coil.push(T((si % 2 === 0 ? -1 : 1) * 0.040, cx.lerp(0.600, 0.542, st), 0.62 + 0.10 * Math.sin(si * 1.9)));
    }
    item('dig', '小肠(空肠与回肠)', [poly(coil, 0.013 * H, 10)],
      { note: '盘在肚脐周围一大团，长 5～7 米；一般的「肚子疼」多在这一带' });

    var cec = W(-0.60, 0.550, 0.58);
    item('dig', '盲肠', [ell(cec, 0.017 * H, 0.017 * H, 0.015 * H, null, 14)],
      { note: '大肠的起点，在右下腹' });
    item('dig', '阑尾', [poly([cec, T(-0.038, 0.542, 0.58), T(-0.028, 0.534, 0.54)], 0.0048 * H, 8)],
      { note: '阑尾炎的典型位置：右下腹压下去痛、松手更痛，常先从肚脐周围开始痛' });
    var ascTop = W(-0.64, 0.634, 0.46);
    item('dig', '升结肠', [poly([W(-0.64, 0.548, 0.54), W(-0.70, 0.590, 0.50), ascTop], 0.0145 * H, 8)],
      { side: '右', note: '沿右侧腹壁往上走' });
    var desTop = W(0.66, 0.636, 0.44);
    item('dig', '横结肠', [poly([ascTop, T(-0.020, 0.626, 0.62), T(0.014, 0.620, 0.64), desTop], 0.0140 * H, 8)],
      { note: '横在上腹，中间会往下垂一点' });
    item('dig', '降结肠', [poly([desTop, W(0.72, 0.596, 0.44), W(0.72, 0.558, 0.46)], 0.0135 * H, 8)],
      { side: '左', note: '沿左侧腹壁往下走' });
    item('dig', '乙状结肠', [poly([W(0.72, 0.556, 0.46), T(0.034, 0.532, 0.52), T(0.006, 0.520, 0.40)], 0.0130 * H, 8)],
      { note: '左下腹一段 S 形，便秘时这里常胀痛' });
    item('dig', '直肠与肛管', [poly([T(0.004, 0.518, 0.28), T(0, 0.500, 0.20), T(0, 0.487, 0.16)], 0.0140 * H, 8)],
      { note: '在骶骨前面往下，末端是肛门；痔和便血多在最下这一小段' });
    /* ---------------- 泌尿 ----------------
       肾在脊柱两侧、腹腔的最后面（贴着后腰），所以肾区的痛是从后腰传出来的 */
    var kid = {};
    [1, -1].forEach(function (side) {
      var sn = side > 0 ? '左' : '右';
      var f = side > 0 ? 0.612 : 0.604;      /* 右肾被肝压着，比左肾低一点 */
      var c = W(side * 0.42, f, 0.15);
      kid[side] = c;
      item('urin', sn + '肾', [ell(c, 0.016 * H, 0.029 * H, 0.017 * H, null, 16)],
        { side: sn, note: '在后腰、最下两根肋骨的下方；肾结石发作是从这里往腹股沟串的剧痛' });
    });
    var bld = T(0, 0.508, 0.55);
    [1, -1].forEach(function (side) {
      var sn = side > 0 ? '左' : '右';
      item('urin', sn + '输尿管', [poly([kid[side], T(side * 0.030, 0.570, 0.24),
        T(side * 0.020, 0.532, 0.34), T(side * 0.010, 0.512, 0.46)], 0.0042 * H, 8)],
        { side: sn, note: '很细，结石卡在这里最痛' });
    });
    item('urin', '膀胱', [ell(bld, 0.025 * H, 0.021 * H, 0.021 * H, null, 16)],
      { note: '在耻骨后面；憋尿时会胀到下腹正中，甚至能在肚皮上摸到' });

    /* ---------------- 生殖（默认隐藏，跟着「显示私密部位」走） ---------------- */
    if (cx.isF) {
      var ut = T(0, 0.521, 0.44);
      item('repro', '子宫', [ell(ut, 0.018 * H, 0.022 * H, 0.014 * H, null, 16)],
        { note: '前倾伏在膀胱上方，不在正中很深处；痛经的位置大致就在下腹正中' });
      var cvx = T(0, 0.504, 0.34);
      item('repro', '子宫颈', [poly([T(0, 0.512, 0.40), cvx], 0.0105 * H, 8)], { note: '子宫的下口，接着阴道' });
      item('repro', '阴道', [poly([cvx, T(0, 0.494, 0.42), T(0, 0.486, 0.52)], 0.0115 * H, 8)],
        { note: '从子宫颈斜向前下走到体外' });
      [1, -1].forEach(function (side) {
        var sn = side > 0 ? '左' : '右';
        var ov = T(side * 0.032, 0.524, 0.34);
        item('repro', sn + '卵巢', [ell(ov, 0.010 * H, 0.008 * H, 0.008 * H, null, 12)],
          { side: sn, note: '排卵前后这一侧下腹可能有几天的隐痛' });
        item('repro', sn + '输卵管', [poly([T(side * 0.014, 0.530, 0.44), T(side * 0.026, 0.532, 0.38), ov], 0.0040 * H, 8)],
          { side: sn });
      });
      item('urin', '尿道', [poly([T(0, 0.500, 0.62), T(0, 0.492, 0.66)], 0.0045 * H, 8)],
        { note: '女性尿道短，所以尿路感染比男性常见得多' });
    } else {
      var pro = T(0, 0.497, 0.46);
      item('repro', '前列腺', [ell(pro, 0.014 * H, 0.012 * H, 0.014 * H, null, 14)],
        { note: '包在尿道外面，位于膀胱下方、直肠前面；增大后会尿不畅' });
      item('urin', '尿道', [poly([bld.clone().setY(0.500 * H), pro, T(0, 0.489, 0.66)], 0.0045 * H, 8)],
        { note: '男性尿道要穿过前列腺再出去，比女性长得多' });
      [1, -1].forEach(function (side) {
        var sn = side > 0 ? '左' : '右';
        var te = new V(side * 0.017 * H, 0.463 * H, 0.028 * H);
        item('repro', sn + '睾丸', [ell(te, 0.014 * H, 0.017 * H, 0.013 * H, null, 14)],
          { side: sn, note: '悬在体外，温度比体内低一点；突然剧痛要当急症处理' });
        item('repro', sn + '输精管', [poly([te.clone().add(new V(0, 0.014 * H, -0.004 * H)),
          new V(side * 0.020 * H, 0.492 * H, 0.014 * H), pro.clone().add(new V(side * 0.008 * H, 0.006 * H, 0))], 0.0035 * H, 8)],
          { side: sn });
      });
      var root = T(0, 0.490, 0.80);
      item('repro', '阴茎(阴茎体)', [tube(root,
        new V(0, root.y - 0.018 * H, root.z + 0.045 * H), 0.017 * H, 0.015 * H, { seg: 14, steps: 3, round1: true })],
        { note: '里面是两条勃起组织和尿道，根部还有一段埋在体内' });
    }
    /* ---------------- 内分泌 ---------------- */
    item('endo', '甲状腺', [
      ell(T(0.014, 0.831, 0.55), 0.011 * H, 0.015 * H, 0.010 * H, null, 14),
      ell(T(-0.014, 0.831, 0.55), 0.011 * H, 0.015 * H, 0.010 * H, null, 14),
      tube(T(-0.008, 0.836, 0.60), T(0.008, 0.836, 0.60), 0.005 * H, 0.005 * H, { seg: 10, steps: 2 })
    ], { note: '骑在气管前面、喉结下方；管新陈代谢，肿大时脖子前面会变粗' });
    [1, -1].forEach(function (side) {
      var sn = side > 0 ? '左' : '右';
      item('endo', sn + '肾上腺', [ell(W(side * 0.36, 0.633, 0.16), 0.011 * H, 0.007 * H, 0.009 * H, null, 12)],
        { side: sn, note: '压在肾的上端，分泌应激和调节血压的激素' });
    });
    item('endo', '垂体', [ell(new V(0, 0.937 * H, cx.headZ - 0.002 * H), 0.005 * H, 0.005 * H, 0.005 * H, null, 12)],
      { note: '在颅底正中的小窝里，指挥全身其它内分泌腺' });

    /* ---------------- 脑与脊髓 ---------------- */
    [1, -1].forEach(function (side) {
      var sn = side > 0 ? '左' : '右';
      item('nerve', sn + '大脑半球', [ell(new V(side * 0.018 * H, 0.958 * H, cx.headZ - 0.004 * H),
        0.021 * H, 0.032 * H, 0.040 * H, null, 18)],
        { side: sn, note: '左半球管右半身，右半球管左半身' });
    });
    item('nerve', '小脑', [ell(new V(0, 0.920 * H, cx.headZ - 0.030 * H), 0.026 * H, 0.013 * H, 0.017 * H, null, 14)],
      { note: '在后脑勺下方，管平衡和动作的协调' });
    item('nerve', '脑干', [poly([new V(0, 0.941 * H, cx.headZ - 0.008 * H),
      new V(0, 0.912 * H, cx.headZ - 0.014 * H), cx.spine(0.884).add(new V(0, 0, -0.010 * H))], 0.0090 * H, 10)],
      { note: '连接大脑和脊髓，呼吸心跳的中枢在这里' });

    var cord = [];
    for (var cf = 0.882; cf > 0.620; cf -= 0.016) cord.push(new V(0, cf * H, cx.spineZ(cf) - 0.013 * H));
    item('nerve', '脊髓', [poly(cord, 0.0075 * H, 10)],
      { note: '走在椎骨后方的骨管里，成年人只到第 1 腰椎附近就结束' });
    var tail = [];
    for (var tf = 0.622; tf > 0.552; tf -= 0.014) tail.push(new V(0, tf * H, cx.spineZ(tf) - 0.012 * H));
    item('nerve', '马尾(腰骶神经根)', [poly(tail, 0.0060 * H, 8)],
      { note: '脊髓末端散开的一束神经根；腰间盘压到的通常就是这里的某一根' });

    ['l', 'r'].forEach(function (k) {
      var b = cx.limb[k], sn = b.sn, side = b.side;
      var mid = b.hip.clone().lerp(b.knee, 0.55);
      item('nerve', sn + '坐骨神经', [poly([
        new V(side * 0.024 * H, 0.548 * H, cx.spineZ(0.548) - 0.008 * H),
        new V(side * 0.040 * H, 0.518 * H, -0.026 * H),
        new V(side * 0.038 * H, 0.498 * H, -0.030 * H),
        new V(mid.x, mid.y, mid.z - 0.030 * H),
        new V(b.knee.x, b.knee.y + 0.030 * H, b.knee.z - 0.034 * H)
      ], 0.0055 * H, 8)], { side: sn, note: '全身最粗的神经：腰骶神经根被压到时，痛和麻会从臀部一路串到小腿' });
    });

    /* ---------------- 淋巴 ---------------- */
    item('lymph', '脾', [ell(W(0.58, 0.650, 0.28), 0.019 * H, 0.026 * H, 0.016 * H, null, 16)],
      { note: '在左侧肋弓深处、胃的后外方；正常摸不到，撞击可能撕裂' });
    /** 沿一条折线撒一串淋巴结 */
    function nodes(pts, n, r) {
      var c = new THREE.CatmullRomCurve3(pts), out = [];
      for (var i = 0; i < n; i++) {
        var p = c.getPoint(n === 1 ? 0.5 : i / (n - 1));
        out.push(ell(p, r, r * 1.15, r, null, 10));
      }
      return out;
    }
    [1, -1].forEach(function (side) {
      var sn = side > 0 ? '左' : '右';
      item('lymph', sn + '颈部淋巴结群', nodes([T(side * 0.026, 0.850, 0.30),
        T(side * 0.034, 0.826, 0.24), T(side * 0.036, 0.800, 0.20)], 6, 0.0055 * H),
        { side: sn, note: '嗓子发炎、牙痛时这一串会肿起来、按着疼' });
      item('lymph', sn + '腋窝淋巴结群', nodes([new V(side * cx.sw * 0.32, 0.758 * H, 0),
        new V(side * cx.sw * 0.38, 0.744 * H, -0.004 * H)], 5, 0.0055 * H),
        { side: sn, note: '收上肢和乳房的淋巴，自查时要顺手摸一下' });
      item('lymph', sn + '腹股沟淋巴结群', nodes([T(side * 0.032, 0.516, 0.66),
        T(side * 0.044, 0.502, 0.62)], 5, 0.0055 * H),
        { side: sn, note: '收下肢和外生殖器的淋巴，脚上有伤口时也可能肿' });
    });
  }

  window.InnerOrgans = { build: build };
})();

